#!/usr/bin/env bash
# Install the "Benchmark Status" desktop launcher on the Mac.
#
# Double-clicking it reads the box's live progress.json and opens the formatted page --
# `remote-ollama-mac benchmark-status --route auto --html`, with no terminal in the way.
#
# The launcher is GENERATED here rather than committed as a finished bundle for two reasons: it must
# carry the absolute path of the checkout it was installed from (the first hand-built copy hardcoded
# one operator's home directory and would have opened an error page forever on anybody else's
# clone), and a .app is a directory of binaries that reviews as an opaque blob in a diff.
#
#   ./scripts/install-benchmark-status-app.sh                       # ~/Desktop
#   BENCHMARK_STATUS_APP_DIR=~/Applications ./scripts/install-...   # somewhere else
#
# Re-running is how you update it; the install is idempotent.
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_DIR="$(cd "$ROOT_DIR/../.." && pwd)"
APP_DIR="${BENCHMARK_STATUS_APP_DIR:-$HOME/Desktop}"
APP="$APP_DIR/Benchmark Status.app"

# Overridable so the test can exercise the guard, and the build, from either machine.
INSTALL_SYSTEM="${BENCHMARK_STATUS_INSTALL_SYSTEM:-$(uname -s)}"
if [ "$INSTALL_SYSTEM" != "Darwin" ]; then
  cat >&2 <<'MSG'
install-benchmark-status-app.sh installs a macOS .app bundle and must run on the Mac.

The Ubuntu box has no desktop to launch it from. To read the run from there, use the
command this launcher wraps:

  ./bin/remote-ollama-mac benchmark-status
MSG
  exit 2
fi

mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Benchmark Status</string>
  <key>CFBundleDisplayName</key><string>Benchmark Status</string>
  <key>CFBundleIdentifier</key><string>com.komplexmojo.agent-kernel.benchmark-status</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>benchmark-status</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
PLIST

# REPO is substituted, not expanded at launch: the bundle can be moved anywhere, and Finder gives it
# no working directory to infer one from.
cat > "$APP/Contents/MacOS/benchmark-status" <<SH
#!/bin/bash
# GENERATED by tools/remote-ollama-control/scripts/install-benchmark-status-app.sh -- edit that,
# then re-run it. Changes made here are lost on the next install.
#
# Launched from Finder, so it inherits almost no environment -- notably NOT nvm's PATH. Every
# failure must still END in an open page: a launcher that exits quietly looks identical to a healthy
# run with nothing to say, which is the confusion this whole benchmark rig exists to remove.
REPO="$REPO_DIR"
SH
cat >> "$APP/Contents/MacOS/benchmark-status" <<'SH'
OUT="$HOME/.local/state/agent-kernel/benchmark-status.html"
mkdir -p "$(dirname "$OUT")"

# Takes the message as an ARGUMENT. Piping into it would run it in a subshell, where its `exit`
# ends only that subshell -- the script would then carry on to the success path and exit 0, having
# reported failure and success at the same time.
show_error() {
  {
    printf '%s' '<!doctype html><html><head><meta charset="utf-8"><title>Benchmark status</title>
<style>:root{color-scheme:light dark}body{margin:0;padding:48px;font:14px/1.6 -apple-system,
BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif}h1{font-size:19px;margin:0 0 6px}
p{color:#8a8f98;margin:0 0 22px}pre{background:rgba(127,127,127,.12);padding:16px 18px;
border-radius:8px;overflow-x:auto;white-space:pre-wrap;font-size:12.5px;line-height:1.5}
code{background:rgba(127,127,127,.14);padding:1px 5px;border-radius:4px}</style></head><body>
<h1>Could not read the benchmark</h1><p>The launcher ran, but the status command did not return a
page.</p><pre>'
    printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
    printf '%s' '</pre><p>Usual causes: the Mac is off the LAN and the external route is closed,
<code>ssh-add</code> has no key loaded after a reboot, or the box is down.</p></body></html>'
  } > "$OUT"
  open "$OUT"
  exit 1
}

# nvm installs node outside any PATH a GUI app inherits. Probe rather than hardcode a version:
# pinning one would break silently at the next node upgrade.
NODE_BIN=""
for candidate in /opt/homebrew/bin/node /usr/local/bin/node; do
  [ -x "$candidate" ] && NODE_BIN="$candidate" && break
done
if [ -z "$NODE_BIN" ]; then
  NODE_BIN="$(/bin/ls -1d "$HOME"/.nvm/versions/node/*/bin/node 2>/dev/null | sort -V | tail -1)"
fi
[ -x "$NODE_BIN" ] || show_error "no node interpreter found (looked in Homebrew, /usr/local and ~/.nvm)"

export PATH="$(dirname "$NODE_BIN"):/usr/bin:/bin:/usr/sbin:/sbin"
cd "$REPO/tools/remote-ollama-control" 2>/dev/null || show_error "checkout not found at $REPO"

# --route auto probes the LAN first and falls back to the external path, so the same icon works
# from home and away.
if ! output=$(./bin/remote-ollama-mac benchmark-status --route auto --html "$OUT" 2>&1); then
  show_error "$output"
fi

open "$OUT"
SH
chmod +x "$APP/Contents/MacOS/benchmark-status"

# The icon is drawn here rather than committed so no binary enters the diff. Pure stdlib: a flat
# PNG is zlib plus chunk framing. Skipped, not fatal, where the macOS image tools are absent -- the
# launcher works without an icon, and this script is also run by the test suite.
if command -v iconutil >/dev/null 2>&1 && command -v sips >/dev/null 2>&1; then
  WORK="$(mktemp -d)"
  trap 'rm -rf "$WORK"' EXIT
  python3 - "$WORK/icon-1024.png" <<'PY'
import zlib, struct, sys

N = 1024
BG = (22, 27, 34)
BARS = [((110, 155, 255), 0.42), ((63, 185, 132), 0.62), ((240, 120, 95), 0.86)]
R, M = int(N * 0.22), int(N * 0.08)

def inside(x, y, x0, y0, x1, y1, r):
    cx, cy = min(max(x, x0 + r), x1 - r), min(max(y, y0 + r), y1 - r)
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r

rows = [[(*BG, 255) if inside(x, y, M, M, N - M, N - M, R) else (0, 0, 0, 0)
         for x in range(N)] for y in range(N)]

# Three bars climbing toward the qualification bar they are measured against.
base, bw, gap = int(N * 0.76), int(N * 0.13), int(N * 0.075)
left = (N - (3 * bw + 2 * gap)) // 2
for i, (colour, height) in enumerate(BARS):
    bx = left + i * (bw + gap)
    top = base - int((base - N * 0.26) * height)
    for y in range(top, base):
        for x in range(bx, bx + bw):
            if inside(x, y, bx, top, bx + bw, base, bw // 2):
                rows[y][x] = (*colour, 255)

line = int(N * 0.30)
for y in range(line, line + int(N * 0.018)):
    for x in range(left - int(N * 0.04), left + 3 * bw + 2 * gap + int(N * 0.04)):
        if (x // int(N * 0.045)) % 2 == 0:
            rows[y][x] = (139, 148, 158, 255)

raw = b''.join(b'\x00' + bytes(v for p in row for v in p) for row in rows)
def chunk(tag, data):
    body = tag + data
    return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xffffffff)
open(sys.argv[1], 'wb').write(
    b'\x89PNG\r\n\x1a\n'
    + chunk(b'IHDR', struct.pack('>IIBBBBB', N, N, 8, 6, 0, 0, 0))
    + chunk(b'IDAT', zlib.compress(raw, 9))
    + chunk(b'IEND', b''))
PY
  mkdir -p "$WORK/icon.iconset"
  for size in 16 32 128 256 512; do
    sips -z "$size" "$size" "$WORK/icon-1024.png" \
      --out "$WORK/icon.iconset/icon_${size}x${size}.png" >/dev/null
    sips -z "$((size * 2))" "$((size * 2))" "$WORK/icon-1024.png" \
      --out "$WORK/icon.iconset/icon_${size}x${size}@2x.png" >/dev/null
  done
  iconutil -c icns "$WORK/icon.iconset" -o "$APP/Contents/Resources/icon.icns"
else
  echo "note: iconutil/sips unavailable — installed without a custom icon" >&2
fi

# Finder caches bundle metadata; without this it keeps showing the previous icon.
touch "$APP"

echo "Installed: $APP"
echo "Reads:     $REPO_DIR"
echo "Opens:     \$HOME/.local/state/agent-kernel/benchmark-status.html"
