#!/usr/bin/env bash
# Install a desktop launcher that opens the benchmark status page.
#
# Double-clicking it runs `remote-ollama-mac benchmark-status --route auto --html` and opens the
# result. Two forms, because macOS privacy protection makes the choice a real one:
#
#   app      a .app bundle with a custom icon and no terminal window. macOS refuses it access to a
#            checkout under ~/Documents, ~/Desktop or ~/Downloads until it is granted Full Disk
#            Access, and rebuilding the bundle can invalidate that grant.
#   command  a .command script. Double-clicking runs it under Terminal, which already holds that
#            grant, so it needs no permission and survives reinstalls. A terminal window appears.
#   both     install each, and use whichever suits.
#
#   ./scripts/install-benchmark-status-launcher.sh                  # app (default)
#   ./scripts/install-benchmark-status-launcher.sh command
#   ./scripts/install-benchmark-status-launcher.sh both
#   BENCHMARK_STATUS_APP_DIR=~/Applications ./scripts/install-...   # somewhere other than ~/Desktop
#
# Both forms are GENERATED rather than committed: each must carry the absolute path of the checkout
# it was installed from (Finder gives a launcher no working directory to infer one from), and a .app
# is a directory of binaries that reviews as an opaque blob in a diff.
#
# Re-running is how you update them; the install is idempotent.
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_DIR="$(cd "$ROOT_DIR/../.." && pwd)"
APP_DIR="${BENCHMARK_STATUS_APP_DIR:-$HOME/Desktop}"
APP="$APP_DIR/Benchmark Status.app"
COMMAND_FILE="$APP_DIR/Benchmark Status.command"

MODE="${1:-app}"
case "$MODE" in
  app|command|both) ;;
  *)
    echo "usage: $(basename "$0") [app|command|both]" >&2
    exit 2
    ;;
esac

# Overridable so the test can exercise the guard, and the build, from either machine.
INSTALL_SYSTEM="${BENCHMARK_STATUS_INSTALL_SYSTEM:-$(uname -s)}"
if [ "$INSTALL_SYSTEM" != "Darwin" ]; then
  cat >&2 <<'MSG'
install-benchmark-status-launcher.sh installs a macOS launcher and must run on the Mac.

The Ubuntu box has no desktop to launch it from. To read the run from there, use the
command this launcher wraps:

  ./bin/remote-ollama-mac benchmark-status
MSG
  exit 2
fi

# $1 = destination path, $2 = what to name in the Full Disk Access instructions. Both forms run the
# same body: a second copy would drift, and the failure handling below is the part most worth not
# having two of.
write_launcher() {
  local destination="$1"
  local grant_target="$2"

  cat > "$destination" <<SH
#!/bin/bash
# GENERATED by tools/remote-ollama-control/scripts/install-benchmark-status-launcher.sh -- edit
# that, then re-run it. Changes made here are lost on the next install.
#
# Launched from Finder, so it inherits almost no environment -- notably NOT nvm's PATH. Every
# failure must still END in an open page: a launcher that exits quietly looks identical to a healthy
# run with nothing to say, which is the confusion this whole benchmark rig exists to remove.
REPO="$REPO_DIR"
GRANT_TARGET="$grant_target"
SH

  cat >> "$destination" <<'SH'
OUT="$HOME/.local/state/agent-kernel/benchmark-status.html"
mkdir -p "$(dirname "$OUT")"

# Takes the message as an ARGUMENT ($1) plus the remediation to show ($2). Piping into it would run
# it in a subshell, where its `exit` ends only that subshell -- the script would then carry on to
# the success path and exit 0, having reported failure and success at the same time.
#
# The remediation is chosen by the CALLER rather than fixed here, because the generic network/ssh
# advice actively misdirects for the failure this hits most: macOS refusing access to the checkout,
# which no amount of checking the LAN explains.
show_error() {
  {
    printf '%s' '<!doctype html><html><head><meta charset="utf-8"><title>Benchmark status</title>
<style>:root{color-scheme:light dark}body{margin:0;padding:48px;font:14px/1.6 -apple-system,
BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif}h1{font-size:19px;margin:0 0 6px}
p{color:#8a8f98;margin:0 0 22px}pre{background:rgba(127,127,127,.12);padding:16px 18px;
border-radius:8px;overflow-x:auto;white-space:pre-wrap;font-size:12.5px;line-height:1.5}
ol{color:#8a8f98;margin:0 0 22px;padding-left:22px}li{margin-bottom:5px}
code{background:rgba(127,127,127,.14);padding:1px 5px;border-radius:4px}</style></head><body>
<h1>Could not read the benchmark</h1><p>The launcher ran, but the status command did not return a
page.</p><pre>'
    printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
    printf '%s' '</pre>'
    printf '%s' "$2"
    printf '%s' '</body></html>'
  } > "$OUT"
  open "$OUT"
  exit 1
}

NETWORK_HINT='<p>Usual causes: the Mac is off the LAN and the external route is closed,
<code>ssh-add</code> has no key loaded after a reboot, or the box is down.</p>'

# macOS blocks apps from Desktop/Documents/Downloads until granted. The checkout lives in one of
# them, so a launcher double-clicked from Finder is refused with EPERM while the very same command
# works from a terminal -- Terminal already holds the grant. That asymmetry is what makes this worth
# naming outright: nothing about the message points at privacy settings.
PERMISSION_HINT="<p><strong>macOS is blocking this launcher from the checkout</strong> &mdash; not a
network problem. The repository is inside a protected folder, and $GRANT_TARGET has no access to it
yet.</p>
<ol>
<li>Open System Settings &rarr; Privacy &amp; Security &rarr; <strong>Full Disk Access</strong></li>
<li>Press <strong>+</strong>, choose <code>$GRANT_TARGET</code>, and switch it on</li>
<li>Launch it again</li>
</ol>
<p>To avoid the permission entirely, run the command from a terminal:
<code>./bin/remote-ollama-mac benchmark-status</code></p>"

# nvm installs node outside any PATH a GUI app inherits. Probe rather than hardcode a version:
# pinning one would break silently at the next node upgrade.
NODE_BIN=""
for candidate in /opt/homebrew/bin/node /usr/local/bin/node; do
  [ -x "$candidate" ] && NODE_BIN="$candidate" && break
done
if [ -z "$NODE_BIN" ]; then
  NODE_BIN="$(/bin/ls -1d "$HOME"/.nvm/versions/node/*/bin/node 2>/dev/null | sort -V | tail -1)"
fi
[ -x "$NODE_BIN" ] || show_error \
  "no node interpreter found (looked in Homebrew, /usr/local and ~/.nvm)" "$NETWORK_HINT"

export PATH="$(dirname "$NODE_BIN"):/usr/bin:/bin:/usr/sbin:/sbin"

# A blocked directory and a missing one both fail this cd. Distinguish them: reporting "checkout not
# found" for a permissions refusal sends you looking for a directory that is sitting right there.
if ! cd_error=$(cd "$REPO/tools/remote-ollama-control" 2>&1); then
  case "$cd_error" in
    *"not permitted"*|*"ermission denied"*) show_error "$cd_error" "$PERMISSION_HINT" ;;
    *) show_error "checkout not found at $REPO" "$NETWORK_HINT" ;;
  esac
fi
cd "$REPO/tools/remote-ollama-control"

# --route auto probes the LAN first and falls back to the external path, so the same launcher works
# from home and away.
if ! output=$(./bin/remote-ollama-mac benchmark-status --route auto --html "$OUT" 2>&1); then
  # Match only "Operation not permitted", which is the TCC refusal. NOT "Permission denied":
  # that is ssh failing to authenticate, and pointing at privacy settings for a missing key would
  # simply swap one wrong diagnosis for another.
  case "$output" in
    *"not permitted"*) show_error "$output" "$PERMISSION_HINT" ;;
    *) show_error "$output" "$NETWORK_HINT" ;;
  esac
fi

open "$OUT"
exit 0
SH
  chmod +x "$destination"
}

install_app() {
  mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

  cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Benchmark Status</string>
  <key>CFBundleDisplayName</key><string>Benchmark Status</string>
  <key>CFBundleIdentifier</key><string>com.komplexmojo.agent-kernel.benchmark-status</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>benchmark-status</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
PLIST

  write_launcher "$APP/Contents/MacOS/benchmark-status" "Benchmark Status.app"
  install_icon
  # Finder caches bundle metadata; without this it keeps showing the previous icon.
  touch "$APP"
  echo "Installed: $APP"
}

install_command() {
  # A .command opens in Terminal, which already holds the Full Disk Access grant -- so this form
  # needs no permission and keeps working after a reinstall. Terminal is what would need the grant
  # in the unlikely case it lacks one, so that is what the hint names here.
  write_launcher "$COMMAND_FILE" "Terminal"
  echo "Installed: $COMMAND_FILE"
}

# The icon is drawn here rather than committed so no binary enters the diff. Pure stdlib: a flat PNG
# is zlib plus chunk framing. Skipped, not fatal, where the macOS image tools are absent -- the
# launcher works without an icon, and this script is also run by the test suite.
install_icon() {
  if ! command -v iconutil >/dev/null 2>&1 || ! command -v sips >/dev/null 2>&1; then
    echo "note: iconutil/sips unavailable — installed without a custom icon" >&2
    return 0
  fi

  local work
  work="$(mktemp -d)"
  python3 - "$work/icon-1024.png" <<'PY'
import zlib, struct, sys

N = 1024
BG = (22, 27, 34)
BARS = [((110, 155, 255), 0.42), ((63, 185, 132), 0.62), ((240, 120, 95), 0.86)]
R, M = int(N * 0.22), int(N * 0.08)

def inside(x, y, x0, y0, x1, y1, r):
    cx, cy = min(max(x, x0 + r), x1 - r), min(max(y, y0 + r), y1 - r)
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r

rows = [[(*BG, 255) if inside(x, y, M, M, N - M, N - M, R) else (0, 0, 0, 0)
         for x in range(N)] for y in range(N)]

# Three bars climbing toward the qualification bar they are measured against.
base, bw, gap = int(N * 0.76), int(N * 0.13), int(N * 0.075)
left = (N - (3 * bw + 2 * gap)) // 2
for i, (colour, height) in enumerate(BARS):
    bx = left + i * (bw + gap)
    top = base - int((base - N * 0.26) * height)
    for y in range(top, base):
        for x in range(bx, bx + bw):
            if inside(x, y, bx, top, bx + bw, base, bw // 2):
                rows[y][x] = (*colour, 255)

line = int(N * 0.30)
for y in range(line, line + int(N * 0.018)):
    for x in range(left - int(N * 0.04), left + 3 * bw + 2 * gap + int(N * 0.04)):
        if (x // int(N * 0.045)) % 2 == 0:
            rows[y][x] = (139, 148, 158, 255)

raw = b''.join(b'\x00' + bytes(v for p in row for v in p) for row in rows)
def chunk(tag, data):
    body = tag + data
    return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xffffffff)
open(sys.argv[1], 'wb').write(
    b'\x89PNG\r\n\x1a\n'
    + chunk(b'IHDR', struct.pack('>IIBBBBB', N, N, 8, 6, 0, 0, 0))
    + chunk(b'IDAT', zlib.compress(raw, 9))
    + chunk(b'IEND', b''))
PY

  mkdir -p "$work/icon.iconset"
  local size
  for size in 16 32 128 256 512; do
    sips -z "$size" "$size" "$work/icon-1024.png" \
      --out "$work/icon.iconset/icon_${size}x${size}.png" >/dev/null
    sips -z "$((size * 2))" "$((size * 2))" "$work/icon-1024.png" \
      --out "$work/icon.iconset/icon_${size}x${size}@2x.png" >/dev/null
  done
  iconutil -c icns "$work/icon.iconset" -o "$APP/Contents/Resources/icon.icns"
  rm -rf "$work"
}

# Written as plain conditionals on purpose: `[ A ] || [ B ] && install` parses as (A||B) && install,
# which evaluates to false for the mode it does not match -- and under `set -e` that false ends the
# script, so `command` would have exited before installing anything.
if [ "$MODE" = "app" ] || [ "$MODE" = "both" ]; then
  install_app
fi
if [ "$MODE" = "command" ] || [ "$MODE" = "both" ]; then
  install_command
fi

echo "Reads:     $REPO_DIR"
echo "Opens:     \$HOME/.local/state/agent-kernel/benchmark-status.html"
exit 0
